import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=path=>fs.readFileSync(new URL(`../${path}`,import.meta.url),'utf8');

test('Family Home uses the structural editorial renderer and mobile composition',()=>{
  const mobile=read('src/styles/home-responsive.css');
  const layout=read('src/styles/home-responsive.css');
  const index=read('src/styles/index.css');
  const controller=read('src/runtime/native-family-v17-controller.js');
  const renderer=read('src/runtime/native-home-editorial.js');
  assert.match(index,/@import '\.\/home-responsive\.css';/);
  assert.ok(layout.indexOf('Source: home-editorial-layout.css')<layout.indexOf('Source: home-mobile-polish.css'));
  assert.match(controller,/renderEditorialHome/);
  assert.match(controller,/route==='dashboard'\)return renderEditorialHome\(\)/);
  assert.match(renderer,/home-editorial-layout/);
  assert.match(renderer,/home-editorial-index/);
  assert.match(renderer,/Our family, connected\./);
  assert.match(renderer,/#families/);
  assert.match(renderer,/home-editorial-lead/);
  assert.match(renderer,/home-editorial-story/);
  assert.match(renderer,/home-editorial-people/);
  assert.match(layout,/\.home-editorial-index\{display:grid/);
  assert.match(layout,/@media\(max-width:720px\)/);
  assert.match(layout,/grid-template-columns:1fr 1fr/);
  assert.match(mobile,/data-experience="family"\]\[data-route="dashboard"/);
  assert.match(mobile,/min-height:0!important/);
  assert.match(mobile,/grid-template-columns:repeat\(3,minmax\(0,1fr\)\)!important/);
  const withoutScrollbarRules=mobile.replace(/[^{}]*::-webkit-scrollbar\{[^{}]*\}/g,'');
  assert.doesNotMatch(withoutScrollbarRules,/display:none/);
});
